const slugify = (t) => t.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);

async function playlist(id) {
  const html = await (await fetch(`https://www.youtube.com/playlist?list=${id}`, { headers: UA })).text();
  const data = JSON.parse(html.match(/var ytInitialData = (\{.*?\});<\/script>/s)[1]);
  const videos = [];
  const walk = (o) => {
    if (Array.isArray(o)) return o.forEach(walk);
    if (o && typeof o === "object") {
      const l = o.lockupViewModel;
      if (l?.contentId && l.metadata?.lockupMetadataViewModel?.title?.content) videos.push({ id: l.contentId, title: l.metadata.lockupMetadataViewModel.title.content });
      Object.values(o).forEach(walk);
    }
  };
  walk(data);
  const seen = new Set();
  return { id, title: data.metadata.playlistMetadataRenderer.title, videos: videos.filter((v) => (seen.has(v.id) ? false : seen.add(v.id))) };
}
async function single(id) {
  const r = await fetch(`https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${id}&format=json`, { headers: UA });
  if (!r.ok) throw new Error(`oembed ${id} ${r.status}`);
  return { id, title: (await r.json()).title };
}
async function thumb(id) {
  fs.mkdirSync(path.join(OUT, "public/video-thumbs"), { recursive: true });
  for (const name of ["maxresdefault", "sddefault", "hqdefault"]) {
    const r = await fetch(`https://i.ytimg.com/vi/${id}/${name}.jpg`);
    if (!r.ok) continue;
    let img = sharp(Buffer.from(await r.arrayBuffer()));
    const m = await img.metadata();
    if (name !== "maxresdefault") { const h = Math.round((m.width * 9) / 16); img = img.extract({ left: 0, top: Math.round((m.height - h) / 2), width: m.width, height: h }); } // drop the letterbox bars
    await img.resize(640, 360, { fit: "cover" }).webp({ quality: 62 }).toFile(path.join(OUT, `public/video-thumbs/${id}.webp`));
    return true;
  }
  return false;
}

