import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { renderMaintenancePage } from "./maintenance-page.mjs";

/** Writes src/maintenance-html.ts from the page source. Run `pnpm --filter @jerryqiu/sites maintenance:build` after editing it. */
const out = fileURLToPath(new URL("../src/maintenance-html.ts", import.meta.url));
const html = renderMaintenancePage();
writeFileSync(
  out,
  `// Generated by scripts/build-maintenance.mjs from scripts/maintenance-page.mjs. Do not edit; edit the source and rebuild.\nexport const maintenanceHtml = ${JSON.stringify(html)};\n`,
);
console.log(`maintenance page: ${html.length} bytes -> src/maintenance-html.ts`);
