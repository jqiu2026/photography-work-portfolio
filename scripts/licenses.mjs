// Generates THIRD_PARTY_LICENSES.md from the production dependency tree and fails on copyleft licenses.
// usage: node scripts/licenses.mjs
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const json = JSON.parse(execSync("pnpm licenses list --prod -r --json", { maxBuffer: 1e9 }).toString());
const rows = [];
for (const [license, pkgs] of Object.entries(json))
  for (const p of pkgs) rows.push({ name: p.name, versions: (p.versions || []).join(", "), license });
rows.sort((a, b) => a.name.localeCompare(b.name));
const bad = rows.filter((r) => /(^|\W)(A?GPL|SSPL|BUSL|Commons Clause)/i.test(r.license));
const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] || 0) + 1;
writeFileSync(
  "THIRD_PARTY_LICENSES.md",
  `# Third-party licenses\n\nGenerated by \`node scripts/licenses.mjs\` from the production dependency tree of every workspace package (${rows.length} packages). No GPL/AGPL code ships in any bundle.\n\nFonts (Anybody, Hanken Grotesk, Newsreader, Martian Mono) are SIL Open Font License 1.1 (license files verified 2026-10-12 against the google/fonts repository and shipped in packages/ui/licenses/fonts/), self-hosted by next/font and never modified. Icons: lucide (ISC), simple-icons (CC0). Demo images in the docs are generated gradients.\n\nSummary: ${Object.entries(
    counts,
  )
    .map(([k, v]) => `${k} (${v})`)
    .join(
      ", ",
    )}\n\n| Package | Version | License |\n|---|---|---|\n${rows.map((r) => `| ${r.name} | ${r.versions} | ${r.license} |`).join("\n")}\n`,
);
console.log(`${rows.length} packages`, counts);
if (bad.length) {
  console.error("Copyleft/unsuitable licenses:", bad);
  process.exit(1);
}
